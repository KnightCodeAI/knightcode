import { Type } from "typebox";
import { afterEach, describe, expect, it } from "vitest";
import { prepareGeminiWebConversation } from "../src/api/gemini-web-conversation.ts";
import { buildGeminiWebPrompt } from "../src/api/gemini-web-tools.ts";
import { cleanupSessionResources } from "../src/session-resources.ts";
import type { AssistantMessage, Context, TextContent, ToolResultMessage } from "../src/types.ts";
import { normalizeContext } from "../src/utils/transcript.ts";

const assistant: AssistantMessage = {
	role: "assistant",
	api: "gemini-web",
	provider: "gemini-web",
	model: "default",
	content: [{ type: "text", text: "Verified the previous operations." }],
	usage: {
		input: 0,
		output: 0,
		cacheRead: 0,
		cacheWrite: 0,
		totalTokens: 0,
		cost: { input: 0, output: 0, cacheRead: 0, cacheWrite: 0, total: 0 },
	},
	stopReason: "stop",
	timestamp: 100,
};

type TextResult = ToolResultMessage & { content: TextContent[] };

function fixture(count = 24, length = 12_000) {
	const context: Context = {
		systemPrompt: "Respect all permissions. Never edit without approval.",
		tools: [{ name: "read", description: "Read a file", parameters: Type.Object({ path: Type.String() }) }],
		messages: [{ role: "user", content: "Fix the website without changing authentication.", timestamp: 1 }],
	};
	const results: TextResult[] = [];
	for (let index = 0; index < count; index++) {
		const id = `read-${index}`;
		const result: TextResult = {
			role: "toolResult",
			toolCallId: id,
			toolName: "read",
			content: [
				{
					type: "text",
					text: `HEAD-${index}\n${"x".repeat(length / 2)}\nMIDDLE-${index}\n${"y".repeat(length / 2)}\nTAIL-${index}`,
				},
			],
			isError: false,
			timestamp: 3 + index * 2,
		};
		context.messages.push(
			{
				...assistant,
				content: [{ type: "toolCall", id, name: "read", arguments: { path: `source-${index}.tsx` } }],
				stopReason: "toolUse",
				timestamp: 2 + index * 2,
			},
			result,
		);
		results.push(result);
	}
	context.messages.push({ role: "user", content: "Continue the unfinished task.", timestamp: 90 });
	return { context: normalizeContext(context), results };
}

afterEach(() => cleanupSessionResources());

describe("Gemini web compact cold replays", () => {
	it("leaves small histories unchanged", () => {
		const { context } = fixture(3, 4_000);
		expect(buildGeminiWebPrompt(context, 0, true)).toBe(buildGeminiWebPrompt(context));
	});

	it("shortens bulky older results without changing instructions, calls, recent results or local history", () => {
		const { context } = fixture();
		const before = JSON.stringify(context);
		const full = buildGeminiWebPrompt(context);
		const compact = buildGeminiWebPrompt(context, 0, true);
		expect(compact.length).toBeLessThan(full.length / 2);
		expect(compact).toContain("HEAD-0");
		expect(compact).toContain("TAIL-0");
		expect(compact).not.toContain("MIDDLE-0");
		expect(compact).toContain("characters omitted from this older tool output");
		expect(compact).toContain("Re-read any needed source before editing it");
		expect(compact).toContain("do not repeat them");
		expect(compact).toContain("Respect all permissions. Never edit without approval.");
		expect(compact).toContain("Fix the website without changing authentication.");
		expect(compact).toContain("Continue the unfinished task.");
		for (let index = 0; index < 24; index++) expect(compact).toContain(`"path":"source-${index}.tsx"`);
		for (let index = 16; index < 24; index++) expect(compact).toContain(`MIDDLE-${index}`);
		expect(JSON.stringify(context)).toBe(before);
	});

	it("does not shorten history when no source-reading tool is available", () => {
		const { context } = fixture();
		context.messages = context.messages.map((message) =>
			message.role === "system" ? { ...message, toolsAdded: undefined, toolsRemoved: undefined } : message,
		);
		expect(buildGeminiWebPrompt(context, 0, true)).toBe(buildGeminiWebPrompt(context));
	});

	it("preserves errors and permission denials verbatim even when old and large", () => {
		const { context, results } = fixture();
		results[0].isError = true;
		results[0].content = [{ type: "text", text: `Permission denied. ${"Do not edit this file. ".repeat(1_000)}` }];
		expect(buildGeminiWebPrompt(context, 0, true)).toContain(results[0].content[0].text);
		expect(buildGeminiWebPrompt(context, 0, true)).toContain('name="read" id="read-0" error="true"');
	});

	it("keeps the entire latest parallel batch, including batches larger than eight calls", () => {
		const { context, results } = fixture();
		context.messages.push({
			...assistant,
			stopReason: "toolUse",
			content: results.slice(0, 12).map((result, index) => ({
				type: "toolCall" as const,
				id: `latest-${index}`,
				name: "read",
				arguments: { path: `latest-${index}` },
			})),
		});
		context.messages.push(
			...results.slice(0, 12).map((result, index) => ({ ...result, toolCallId: `latest-${index}` })),
		);
		const compact = buildGeminiWebPrompt(context, 0, true);
		for (const result of results.slice(0, 12)) expect(compact).toContain(result.content[0].text);
	});

	it("never shortens newly delivered results on an incremental continuation", () => {
		const { context, results } = fixture();
		const prompt = buildGeminiWebPrompt(context, 1, true);
		for (const result of results) expect(prompt).toContain(result.content[0].text);
		expect(prompt).not.toContain("characters omitted");
	});

	it("does not mistake excerpts for a summary or replace assistant conclusions and tool arguments", () => {
		const { context } = fixture();
		context.messages.push({
			...assistant,
			content: [{ type: "text", text: "Confirmed: CSS fixed; animation work remains." }],
		});
		const compact = buildGeminiWebPrompt(context, 0, true);
		expect(compact).toContain("Confirmed: CSS fixed; animation work remains.");
		expect(compact).toContain('"name":"read","arguments":{"path":"source-0.tsx"}');
	});

	it("lets low-level callers request an unshortened cold replay", () => {
		const { context } = fixture();
		const full = prepareGeminiWebConversation({
			context,
			cookie: "__Secure-1PSID=test",
			model: "default",
			compactHistory: false,
		});
		expect(full.prompt).toBe(buildGeminiWebPrompt(context));
		expect(full.prompt).toContain("MIDDLE-0");
	});

	it.each(["before save", "after save"])("detects changed content inside an omitted region (%s)", (when) => {
		const { context, results } = fixture();
		const input = { context, cookie: "__Secure-1PSID=test", model: "default", sessionId: "changed-excerpt" };
		const prepared = prepareGeminiWebConversation(input);
		if (when === "after save") prepared.save(assistant, ["c1", "r1", "rc1"]);
		results[0].content = [{ type: "text", text: results[0].content[0].text.replace("MIDDLE-0", "CHANGED-0") }];
		expect(buildGeminiWebPrompt(context, 0, true)).not.toContain("CHANGED-0");
		if (when === "before save") prepared.save(assistant, ["c1", "r1", "rc1"]);
		context.messages.push(assistant, { role: "user", content: "Continue", timestamp: 101 });
		expect(prepareGeminiWebConversation(input).metadata).toBeUndefined();
	});

	it("uses compact replay once, then sends only new messages without extra generations", () => {
		const { context } = fixture();
		const input = { context, cookie: "__Secure-1PSID=test", model: "default", sessionId: "compact-prefix" };
		const first = prepareGeminiWebConversation(input);
		expect(first.prompt).not.toContain("MIDDLE-0");
		first.save(assistant, ["c1", "r1", "rc1"]);
		context.messages.push(assistant, { role: "user", content: "Next task", timestamp: 101 });
		const next = prepareGeminiWebConversation(input);
		expect(next.metadata).toEqual(["c1", "r1", "rc1"]);
		expect(next.prompt).toContain("Next task");
		expect(next.prompt).not.toContain("source-0.tsx");
	});

	it("starts fresh when full replay is requested after a compact replay", () => {
		const { context } = fixture();
		const input = { context, cookie: "__Secure-1PSID=test", model: "default", sessionId: "full-after-compact" };
		prepareGeminiWebConversation(input).save(assistant, ["c1", "r1", "rc1"]);
		context.messages.push(assistant, { role: "user", content: "Continue", timestamp: 101 });
		const next = prepareGeminiWebConversation({ ...input, compactHistory: false });
		expect(next.metadata).toBeUndefined();
		expect(next.prompt).toContain("MIDDLE-0");
	});
});
