// Turns the design tokens into CSS custom properties. Run directly (`bun src/tokens/css.ts`) to rewrite tokens.css.
import { writeFileSync } from "node:fs";
import {
	avatarColors,
	colors,
	durations,
	easings,
	fonts,
	fontSizes,
	fontWeights,
	layout,
	letterSpacings,
	lineHeights,
	radii,
	shadows,
	space,
	type Theme,
} from "./tokens.ts";

/** The stylesheet every KnightCode Bots surface loads: shared tokens on :root, theme tokens per theme. */
export function tokensCss(): string {
	const shared = [
		...entries("space", space),
		...entries("radius", radii),
		...entries("font-size", fontSizes),
		...entries("line-height", lineHeights),
		...entries("font-weight", fontWeights),
		...entries("tracking", letterSpacings),
		...entries("duration", durations),
		...entries("ease", easings),
		...entries("font", fonts),
		...entries("layout", {
			...layout,
			settingsDialogWidth: layout.settingsDialog.width,
			settingsDialogHeight: layout.settingsDialog.height,
			createDialogWidth: layout.createDialog.width,
			settingsDialog: undefined,
			createDialog: undefined,
		}),
	];
	const theme = (name: Theme) => [
		`color-scheme: ${name};`,
		...entries("color", colors[name]),
		...entries("avatar", avatarColors[name]),
		...entries("shadow", shadows[name]),
	];
	return [
		"/* Generated by src/tokens/css.ts from tokens.ts. Do not edit. */",
		block(":root", shared),
		block(':root, [data-theme="dark"]', theme("dark")),
		`@media (prefers-color-scheme: light) {\n${indent(block(':root:not([data-theme="dark"])', theme("light")))}\n}`,
		block('[data-theme="light"]', theme("light")),
		"",
	].join("\n\n");
}

function entries(group: string, values: Record<string, string | number | undefined>): string[] {
	return Object.entries(values)
		.filter((entry): entry is [string, string | number] => entry[1] !== undefined && typeof entry[1] !== "object")
		.map(([key, value]) => `--kb-${group}-${kebab(key)}: ${value};`);
}

function kebab(key: string): string {
	return key.replace(/[A-Z]/g, (c) => `-${c.toLowerCase()}`);
}

function block(selector: string, lines: string[]): string {
	return `${selector} {\n${lines.map((line) => `\t${line}`).join("\n")}\n}`;
}

function indent(text: string): string {
	return text
		.split("\n")
		.map((line) => `\t${line}`)
		.join("\n");
}

if (import.meta.main) writeFileSync(new URL("./tokens.css", import.meta.url), tokensCss());
